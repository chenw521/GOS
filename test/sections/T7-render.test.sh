#!/usr/bin/env bash
# gos-map:cmd render
# T7: renderer (three GENERATED views + MANUAL preservation + backup rotation)
# Env: GOS (CLI path), TESTBASE (repo root for sandbox), + assert helpers sourced by runner
T7_DIR=""

t7_setup() {
  T7_DIR="$TESTBASE/test-$(date +%s)-$RANDOM-t7"
  mkdir -p "$T7_DIR" && cd "$T7_DIR" || exit 1
  git init -q . && git commit -q --allow-empty -m root
  echo ".gos/state.json" > .gitignore && git add .gitignore && git commit -q -m gi
}

t7_seed() {
  python3 -c "
import json
p=json.load(open('.gos/project/project.json'))
p['phases']=[{'name':'P1: core','goal':'ship core','status':'active'}]
p['decisions']=[
 {'id':'D-01','title':'Use A & B stack','rationale':'proven combo','birth_phase':'P1: core','status':'open','anchor':None,'covered':False,'covered_by':None},
 {'id':'D-02','title':'pipe | char','rationale':'old way','birth_phase':'P1: core','status':'superseded','anchor':None,'covered':False,'covered_by':None,'supersedes':'D-00'},
]
p['requirements']=[{'id':'R-01','text':'render three views','phase':'P1: core','status':'active'}]
json.dump(p,open('.gos/project/project.json','w'),indent=2)"
}

t7_teardown() { cd "$TESTBASE" >/dev/null 2>&1; rm -rf "$T7_DIR"; }

t7_setup
echo "--- T7: render (three views + manual + backup + governance) ---"

# --- T7.1: render succeeds and writes all three views ---
node "$GOS" init 4 "plat" --project >/dev/null 2>&1
t7_seed
set +e; OUT=$(node "$GOS" render 2>&1); RC=$?; set -e
assert_exit "render exits 0" 0 "$RC"
assert_contains "render output contract" "✓ rendered: DECISIONS.md, ROADMAP.md, REQUIREMENTS.md" "$OUT"
assert_file "DECISIONS.md rendered" ".gos/project/DECISIONS.md"
assert_file "ROADMAP.md rendered" ".gos/project/ROADMAP.md"
assert_file "REQUIREMENTS.md rendered" ".gos/project/REQUIREMENTS.md"

# --- T7.2: DECISIONS.md content — header line 1, table, strikethrough, escaping ---
H1=$(head -n 1 .gos/project/DECISIONS.md)
assert_eq "DECISIONS.md line 1 = GENERATED header" "<!-- GENERATED by gos — edit via gos decision/requirement/phase commands, not this file -->" "$H1"
DEC=$(cat .gos/project/DECISIONS.md)
assert_contains "table header contract" "| ID | Decision | Rationale | Phase | Status |" "$DEC"
assert_contains "amp escaped first (&→&amp;)" "Use A &amp; B stack" "$DEC"
assert_contains "superseded strikethrough on D-02" "~~pipe" "$DEC"
assert_contains "pipe escaped (|→\|)" '\\| char' "$DEC"

# --- T7.3: ROADMAP + REQUIREMENTS rows from project.json ---
assert_contains "ROADMAP P1 row" "| P1: core | ship core | active |" "$(cat .gos/project/ROADMAP.md)"
assert_contains "REQUIREMENTS R-01 row" "R-01" "$(cat .gos/project/REQUIREMENTS.md)"

# --- T7.3b: phase scoping — active + last 2 phases; unknown birth_phase included ---
python3 -c "
import json
p=json.load(open('.gos/project/project.json'))
p['phases']=[{'name':'P1','goal':'g1','status':'done'},{'name':'P2','goal':'g2','status':'done'},{'name':'P3','goal':'g3','status':'done'},{'name':'P4','goal':'g4','status':'active'}]
p['decisions']=[
 {'id':'D-01','title':'ancient','rationale':'','birth_phase':'P1','status':'open','anchor':None,'covered':False,'covered_by':None},
 {'id':'D-02','title':'current','rationale':'','birth_phase':'P4','status':'open','anchor':None,'covered':False,'covered_by':None},
 {'id':'D-03','title':'unknown phase kept','rationale':'','birth_phase':'P0-legacy','status':'open','anchor':None,'covered':False,'covered_by':None},
]
json.dump(p,open('.gos/project/project.json','w'),indent=2)"
node "$GOS" render >/dev/null 2>&1 || true
DECSC=$(cat .gos/project/DECISIONS.md)
if echo "$DECSC" | grep -q 'ancient'; then echo "  ✗ P1 decision (3+ phases back) should be scoped out"; FAIL=$((FAIL+1)); else echo "  ✓ P1 decision scoped out"; PASS=$((PASS+1)); fi
assert_contains "active-phase decision kept" "current" "$DECSC"
assert_contains "unknown birth_phase kept" "unknown phase kept" "$DECSC"

# --- T7.4: MANUAL region preserved across re-render, marker exactly once ---
printf '\n<!-- MANUAL:notes -->\nmy manual note' >> .gos/project/DECISIONS.md
node "$GOS" render >/dev/null 2>&1 || true
DEC2=$(cat .gos/project/DECISIONS.md)
assert_contains "manual note preserved after re-render" "my manual note" "$DEC2"
MC=$(grep -c '^<!-- MANUAL:notes -->$' .gos/project/DECISIONS.md)
assert_eq "manual marker exactly once" "1" "$MC"

# --- T7.5: backup rotation — render 6× keeps ≤5 backup dirs ---
for i in 1 2 3 4 5 6; do node "$GOS" render >/dev/null 2>&1 || true; done
BC=$(ls -1 .gos/archive/render-backup 2>/dev/null | wc -l | tr -d ' ')
if [ "$BC" -le 5 ] && [ "$BC" -ge 1 ]; then echo "  ✓ backup rotation keeps ≤5 dirs (found $BC)"; PASS=$((PASS+1)); else echo "  ✗ backup rotation broken (found ${BC:-0})"; FAIL=$((FAIL+1)); fi

# --- T7.6: no project.json → advisory message, exit 0 ---
t7_teardown; t7_setup
node "$GOS" init 3 "plain task" >/dev/null 2>&1
set +e; OUT=$(node "$GOS" render 2>&1); RC=$?; set -e
assert_exit "render without project.json exits 0" 0 "$RC"
assert_contains "advisory message" "(no project.json — nothing to render)" "$OUT"

# --- T7.7: governance migration — 60 decisions in project.json → status warns ---
t7_teardown; t7_setup
node "$GOS" init 4 "gov" --project >/dev/null 2>&1
python3 -c "
import json
p=json.load(open('.gos/project/project.json'))
p['phases']=[{'name':'P1','goal':'g','status':'active'}]
p['decisions']=[{'id':'D-%02d'%i,'title':'bulk %d'%i,'rationale':'','birth_phase':'P1','status':'open','anchor':None,'covered':False,'covered_by':None} for i in range(1,61)]
json.dump(p,open('.gos/project/project.json','w'),indent=2)"
OUT=$(node "$GOS" status 2>&1)
assert_contains "index large warning fires" "index large" "$OUT"
assert_contains "warning counts 60 entries" "60 entries (>50)" "$OUT"

t7_teardown
