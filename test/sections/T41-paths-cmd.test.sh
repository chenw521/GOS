#!/usr/bin/env bash
# gos-map:fn bin/lib/ops/paths.cjs#fn:cmdPaths bin/lib/core/state.cjs#fn:currentTaskId
# gos-map:cmd paths
# T41: gos paths command — JSON absolute-path output + --markdown README generation idempotent
T41_DIR=""

t41_setup() {
  T41_DIR="$TESTBASE/test-$(date +%s)-$RANDOM-t41"
  mkdir -p "$T41_DIR" && cd "$T41_DIR" || exit 1
}
t41_teardown() { cd "$TESTBASE" >/dev/null 2>&1; rm -rf "$T41_DIR"; }

t41_setup
trap 't41_teardown' EXIT

PASS=0
FAIL=0

echo "--- T41: gos paths (JSON + markdown regen) ---"

git init -q . && git commit -q --allow-empty -m root
node "$GOS" init 1 "t41 paths probe" >/dev/null 2>&1
GOS_INIT_RC=$?
if [ "$GOS_INIT_RC" -eq 0 ]; then
  echo "  ✓ T41.0 sandbox task initialized"; PASS=$((PASS+1))
else
  echo "  ✗ T41.0 init failed (rc=$GOS_INIT_RC)"; FAIL=$((FAIL+1))
fi

# T41.1 JSON valid + project_root correct (stderr banner must not pollute stdout)
set +e
PJSON="$(node "$GOS" paths 2>/dev/null)"
PJRC=$?
set -e
printf '%s' "$PJSON" > paths-out.json
if [ "$PJRC" -eq 0 ] && python3 -c "import json;json.load(open('paths-out.json'))" 2>/dev/null; then
  echo "  ✓ T41.1 paths JSON valid on stdout (rc=0)"; PASS=$((PASS+1))
else
  echo "  ✗ T41.1 paths JSON invalid (rc=$PJRC)"; FAIL=$((FAIL+1))
fi

# T41.2 project_root + absolute paths + dynamic key resolution (active task exists)
set +e
V2="$(python3 - <<'PYEOF'
import json, os
d = json.load(open('paths-out.json'))
pr = d.get('project_root')
if not pr or not os.path.isabs(pr) or os.path.realpath(pr) != os.path.realpath(os.getcwd()):
    print('BAD-ROOT: %r' % pr); raise SystemExit(1)
p = d.get('paths', {})
if len(p) < 26: print('SIZE: %d' % len(p)); raise SystemExit(1)
for k, v in p.items():
    a = v.get('abs')
    if a is None:
        print('NULL-ABS: %s (hint=%r)' % (k, v.get('hint'))); raise SystemExit(1)
    if not os.path.isabs(a): print('REL-ABS: %s -> %r' % (k, a)); raise SystemExit(1)
    if not a.startswith(pr + os.sep) and a != pr: print('ESCAPED: %s -> %r (root %r)' % (k, a, pr)); raise SystemExit(1)
spec = p.get('spec', {}).get('abs', '')
if '/task/' not in spec or not spec.endswith('spec.md'):
    print('DYN-UNRESOLVED: spec abs=%r (active task should resolve <task_id>)' % spec); raise SystemExit(1)
print('OK')
PYEOF
)"
set -e
if [ "$V2" = "OK" ]; then
  echo "  ✓ T41.2 project_root + all-abs + dynamic spec/plan resolved"; PASS=$((PASS+1))
else
  echo "  ✗ T41.2 $V2"; FAIL=$((FAIL+1))
fi

# T41.3 with no active task: dynamic key abs=null + hint (state removed before querying)
set +e
mv .gos/state.json state.bak
PJSON2="$(node "$GOS" paths 2>/dev/null)"
PJ2RC=$?
mv state.bak .gos/state.json
set -e
printf '%s' "$PJSON2" > paths-out2.json
if [ "$PJ2RC" -eq 0 ]; then
  echo "  ✓ T41.3a paths without state exits 0"; PASS=$((PASS+1))
else
  echo "  ✗ T41.3a paths without state rc=$PJ2RC (query must not require a task)"; FAIL=$((FAIL+1))
fi
set +e
V3="$(python3 - <<'PYEOF'
import json
d = json.load(open('paths-out2.json'))
spec = d['paths'].get('spec', {})
if spec.get('abs') is not None:
    print('SHOULD-BE-NULL: %r' % spec.get('abs')); raise SystemExit(1)
if not spec.get('hint'):
    print('HINT-MISSING'); raise SystemExit(1)
print('OK')
PYEOF
)"
set -e
if [ "$V3" = "OK" ]; then
  echo "  ✓ T41.3b dynamic keys abs=null + hint when no task"; PASS=$((PASS+1))
else
  echo "  ✗ T41.3b $V3"; FAIL=$((FAIL+1))
fi

# T41.4 --markdown generates the README: GENERATED header + table carries registry entries + idempotent
set +e
node "$GOS" paths --markdown >/dev/null 2>&1
MKRC=$?
set -e
if [ "$MKRC" -eq 0 ] && head -1 .gos/README.md | grep -q "GENERATED by gos paths --markdown"; then
  echo "  ✓ T41.4a README generated with GENERATED header"; PASS=$((PASS+1))
else
  echo "  ✗ T41.4a README header wrong (rc=$MKRC)"; FAIL=$((FAIL+1))
fi
if grep -q "cache/deps.json" .gos/README.md && grep -q "task/" .gos/README.md && grep -q "logs/truth-receipts.md" .gos/README.md; then
  echo "  ✓ T41.4b README table covers cache/logs/task zones"; PASS=$((PASS+1))
else
  echo "  ✗ T41.4b README table incomplete"; FAIL=$((FAIL+1))
fi
cp .gos/README.md readme-first.txt
node "$GOS" paths --markdown >/dev/null 2>&1
if diff -q readme-first.txt .gos/README.md >/dev/null; then
  echo "  ✓ T41.4c README regen idempotent (no timestamp drift)"; PASS=$((PASS+1))
else
  echo "  ✗ T41.4c README regen NOT idempotent"; FAIL=$((FAIL+1))
fi

# T41.5 contract additive-only: _contract emits the new readmeGenerated key + existing keys unchanged
if node "$GOS" _contract 2>/dev/null | grep -q "readmeGenerated"; then
  echo "  ✓ T41.5 contract additive: readmeGenerated present"; PASS=$((PASS+1))
else
  echo "  ✗ T41.5 readmeGenerated missing from contracts"; FAIL=$((FAIL+1))
fi

echo "--- T41 summary: $PASS passed, $FAIL failed ---"
[ "$FAIL" -eq 0 ]
