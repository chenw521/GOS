const MAP_PATTERNS = {
  js: [
    /^\s*(?:const|let|var)\s+[A-Za-z_$][\w$]*\s*=\s*require\(\s*['"]([^'"]+)['"]\s*\)/,
    /^\s*import\s+[^;'"()]*?\s*from\s+['"]([^'"]+)['"]/,
    /^\s*import\s+['"]([^'"]+)['"]/,
  ],
  py: [
    /^\s*import\s+([A-Za-z_][\w.]*)/,
    /^\s*from\s+([A-Za-z_][\w.]*)\s+import\b/,
  ],
  r: [
    /^\s*source\(\s*['"]?([^'")\s]+)['"]?\s*\)/,
    /^\s*(?:library|require)\(\s*['"]?([\w.]+)['"]?\s*\)/,
    /^\s*(?!#)([A-Za-z][\w.]*)::[\w.]+\(/,
  ],
};

function mapLangOf(ext) {
  if (ext === '.py') return 'py';
  if (ext === '.R' || ext === '.r') return 'r';
  return 'js'; // js/ts family
}

function mapSpecCandidates(spec, fromFile) {
  const lang = mapLangOf(path.extname(fromFile));
  if (lang === 'js') {
    if (!spec.startsWith('./') && !spec.startsWith('../')) return []; // bare specifier → external
    const base = path.posix.normalize(path.posix.join(path.posix.dirname(fromFile), spec));
    const cands = [base];
    if (!path.posix.extname(base)) {
      for (const e of ['.js', '.cjs', '.mjs', '.ts', '.jsx', '.tsx']) cands.push(base + e);
      cands.push(base + '/index.js', base + '/index.ts');
    }
    return cands;
  }
  if (lang === 'py') {
    const base = spec.split('.').join('/');
    const cands = [base + '.py', base + '/__init__.py'];
    // py sibling imports [0.11.2]: Python sys.path[0] = script dir — flat imports
    // (`from manager import X` inside buggy_repo/) resolve file-relative. Without
    // this, subdirectory multi-file repos (benchmark d3/d4 style) silently lose
    // intra-repo edges to externals. Bare (dotless) specs only, root kept first.
    if (!spec.includes('.')) {
      const sib = path.posix.join(path.posix.dirname(fromFile), spec);
      cands.push(sib + '.py', sib + '/__init__.py');
    }
    return cands;
  }
  // R: library()/require()/pkg::func specs are package names (never paths);
  // source('x') resolves root-relative FIRST (R convention: cwd≈project root),
  // then file-relative. [R2-F5]
  if (!/[\\/]/.test(spec) && !/\.[rR]$/.test(spec)) return [];
  const rootRel = path.posix.normalize(spec);
  const fileRel = path.posix.normalize(path.posix.join(path.posix.dirname(fromFile), spec));
  return [rootRel, rootRel + '.R', rootRel + '.r', fileRel, fileRel + '.R', fileRel + '.r'];
}

function mapResolveSpec(spec, fromFile, filesSet) {
  for (const c of mapSpecCandidates(spec, fromFile)) if (filesSet.has(c)) return c;
  return null;
}

function scanSources(root) {
  const files = [];
  let skippedBinary = 0, skippedHuge = 0, skippedDir = 0, unreadableFile = 0;
  const walk = (dir) => {
    let ents;
    try { ents = fs.readdirSync(dir, { withFileTypes: true }); }
    catch { skippedDir++; return; }
    for (const ent of ents) {
      if (MAP_SKIP_DIRS.has(ent.name)) continue;
      // repo-root test sandboxes (test-<timestamp>-*) are not source — excluded at root level only
      if (dir === root && ent.isDirectory() && /^test-/.test(ent.name)) continue;
      const full = path.join(dir, ent.name);
      let st;
      try { st = fs.lstatSync(full); } catch { continue; }
      if (st.isSymbolicLink()) continue;                 // [R1-F9] never follow, never a node
      if (st.isDirectory()) { walk(full); continue; }
      if (!st.isFile()) continue;
      if (!MAP_EXTS.has(path.extname(ent.name))) continue;
      if (ent.name.endsWith('.min.js')) continue;
      files.push(path.relative(root, full).split(path.sep).join('/'));
    }
  };
  walk(root);
  files.sort();
  // Single content read per file (REVIEW #3): pass 1 reads + guards + collects raw
  // (from, spec) pairs; resolution happens AFTER the ok-set is known so guard-skipped
  // files can never become edge targets.
  const scannedOk = new Set();
  const rawPairs = [];
  for (const rel of files) {
    const pats = MAP_PATTERNS[mapLangOf(path.extname(rel))];
    let content;
    try { content = fs.readFileSync(path.join(root, rel), 'utf8'); }
    catch { unreadableFile++; continue; }                // REVIEW #3: vanished/locked mid-scan
    if (content.includes('\u0000')) { skippedBinary++; continue; }        // [R2-F12]
    if (Buffer.byteLength(content, 'utf8') > 1024 * 1024) { skippedHuge++; continue; }
    let maxLine = 0;
    for (const line of content.split('\n')) { if (line.length > maxLine) { maxLine = line.length; if (maxLine > 500 * 1024) break; } }
    if (maxLine > 500 * 1024) { skippedHuge++; continue; }
    scannedOk.add(rel);
    for (const line of content.split('\n')) {
      for (const re of pats) {
        const m = line.match(re);
        if (m && m[1]) rawPairs.push([rel, m[1]]);
      }
    }
  }
  const filesSet = scannedOk;   // resolution universe = admitted files only
  const finalFiles = [...scannedOk].sort();
  const edgesL = []; const externals = [];
  const seenPairs = new Set();   // REVIEW #6: dedupe repeated imports (show renders once)
  for (const [rel, spec] of rawPairs) {
    const resolved = mapResolveSpec(spec, rel, filesSet);
    if (resolved) {
      if (resolved !== rel) {
        const key = rel + '\u0000' + resolved;
        if (!seenPairs.has(key)) { seenPairs.add(key); edgesL.push({ from: rel, to: resolved }); }
      }
    } else {
      const xkey = rel + '\u0000' + spec;
      if (!seenPairs.has(xkey)) { seenPairs.add(xkey); externals.push({ from: rel, spec }); }
    }
  }
  edgesL.sort((a, b) => (a.from + '\u0000' + a.to).localeCompare(b.from + '\u0000' + b.to));
  externals.sort((a, b) => (a.from + '\u0000' + a.spec).localeCompare(b.from + '\u0000' + b.spec));
  return { files: finalFiles, edges: edgesL, externals, skipped_binary: skippedBinary, skipped_huge: skippedHuge, skipped_dir: skippedDir, unreadable_file: unreadableFile };   // frozen key: scan output schema keeps `edges` (local edgesL is a shadow-defense rename)
}

function mapGitInfo(root) {
  const git = (a) => { try { return execFileSync('git', a, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { return null; } };
  if (git(['rev-parse', '--is-inside-work-tree']) !== 'true') return { head: null, worktree_clean: null };
  const head = git(['rev-parse', 'HEAD']);
  if (head === null) return { head: 'unborn', worktree_clean: null };
  const porcelain = git(['status', '--porcelain', '--untracked-files=no']) || '';
  const dirty = porcelain.split('\n').filter((l) => l && !/(^|\/)\.gos\/deps\.json$/.test(l.slice(3).trim()) && !l.endsWith('.gos/deps.json'));
  return { head, worktree_clean: dirty.length === 0 };
}

function fnSetFingerprint(fns) {   // C4 fingerprint: sha16 over the sorted fn-name list — single engine/gate implementation
  return crypto.createHash('sha256').update((fns || []).join('\n'), 'utf8').digest('hex').slice(0, 16);
}

function depsSelfHash(bodyObj) {
  return crypto.createHash('sha256').update(JSON.stringify(bodyObj, null, 2) + '\n', 'utf8').digest('hex');
}

function loadMapIgnore(root) {   // .gos/map-ignore: glob list, tracked; + .md line exemption marker
  const out = new Set();
  try {
    const txt = fs.readFileSync(path.join(root, '.gos', 'map-ignore'), 'utf8');
    for (const l of txt.split('\n')) {
      const t = l.trim();
      if (t && !t.startsWith('#')) out.add(t);
    }
  } catch { /* no list — everything scannable */ }
  return out;
}

const SEMANTIC_EXTS = new Set([...Array.from(MAP_EXTS), '.md', '.sh']);

let _acorn = null;

function acornCtx() {
  try { _acorn = _acorn || require('acorn'); } catch { return { err: 'acorn_missing' }; }
  return {
    parse(src) {
      const opts = { ecmaVersion: 'latest', allowHashBang: true };
      try { return { ast: _acorn.parse(src, Object.assign({ sourceType: 'script' }, opts)) }; }
      catch (e1) {
        // .js ambiguity under "type": "module" — retry as ESM before recording a failure
        try { return { ast: _acorn.parse(src, Object.assign({ sourceType: 'module' }, opts)) }; }
        catch { return { err: 'parse_fail', msg: String(e1.message).split('\n')[0] }; }
      }
    },
  };
}

function semanticUniverse(root) {
  const t = core.trackedFiles(root);
  const ig = loadMapIgnore(root);
  const out = [];
  for (const p of t.exact) {
    const e = path.extname(p), top = p.split('/')[0];
    if (!SEMANTIC_EXTS.has(e)) continue;
    if (top === '.gos' || MAP_SKIP_DIRS.has(top) || top.startsWith('test-')) continue;
    if (ig.has(p) || [...ig].some((g) => g.includes('*') && core.globMatch(g, p))) continue;
    out.push(p);
  }
  return out;
}

function readUniverseLines(root, f) {   // per-line read honoring the .md line exemption
  let src;
  try { src = fs.readFileSync(path.join(root, f), 'utf8'); } catch { return []; }
  return src.split('\n').filter((l) => !l.includes('<!-- gos-map:ignore -->'));
}

